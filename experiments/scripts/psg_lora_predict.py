"""
psg_lora_predict_dim5.py

Batch inference for v2 PSG. Input JSONL rows must contain:
  instruction, input, metadata
Output JSONL rows contain:
  psg_pred, p0, p1, margin_1_minus_0, raw_generation, mode, metadata

Default mode computes next-token logits for "0" and "1".
"""
import argparse, json, os, re, time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, Iterable, List
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
try:
    from peft import PeftModel
except Exception:
    PeftModel = None

def read_jsonl(path: str, max_samples: int = -1):
    n = 0
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip(): continue
            yield json.loads(line)
            n += 1
            if max_samples > 0 and n >= max_samples: break

def batched(it, bs):
    buf = []
    for x in it:
        buf.append(x)
        if len(buf) >= bs:
            yield buf; buf = []
    if buf: yield buf

def build_prompt(tokenizer, obj):
    content = obj.get("instruction", "").strip() + "\n\n" + obj.get("input", "").strip()
    if getattr(tokenizer, "chat_template", None):
        return tokenizer.apply_chat_template([{"role":"user", "content":content}], tokenize=False, add_generation_prompt=True)
    return "<|im_start|>user\n" + content + "<|im_end|>\n<|im_start|>assistant\n"

def load_model(args):
    tok_path = args.tokenizer_path
    if tok_path is None:
        tok_path = args.adapter_path if args.adapter_path and (Path(args.adapter_path) / "tokenizer_config.json").exists() else args.model_path
    print(f"[load] tokenizer={tok_path}")
    tok = AutoTokenizer.from_pretrained(tok_path, trust_remote_code=args.trust_remote_code, use_fast=True)
    tok.padding_side = "left"; tok.truncation_side = "left"
    if tok.pad_token_id is None: tok.pad_token = tok.eos_token
    dtype = {"auto":"auto", "bf16":torch.bfloat16, "fp16":torch.float16, "fp32":torch.float32}[args.dtype]
    print(f"[load] base={args.model_path}")
    model = AutoModelForCausalLM.from_pretrained(args.model_path, trust_remote_code=args.trust_remote_code, torch_dtype=dtype, low_cpu_mem_usage=True)
    if args.adapter_path:
        if PeftModel is None: raise RuntimeError("peft is not installed")
        print(f"[load] adapter={args.adapter_path}")
        model = PeftModel.from_pretrained(model, args.adapter_path)
    device = torch.device(args.device)
    model.to(device); model.eval()
    zero_ids = tok.encode("0", add_special_tokens=False); one_ids = tok.encode("1", add_special_tokens=False)
    if not zero_ids or not one_ids: raise RuntimeError("Cannot tokenize 0/1")
    print(f"[token] zero_id={zero_ids[-1]}, one_id={one_ids[-1]}")
    return tok, model, device, zero_ids[-1], one_ids[-1]

@torch.inference_mode()
def predict_logits(tok, model, device, batch, zero_id, one_id, max_length):
    prompts = [build_prompt(tok, x) for x in batch]
    enc = tok(prompts, return_tensors="pt", padding=True, truncation=True, max_length=max_length)
    enc = {k:v.to(device) for k,v in enc.items()}
    out = model(**enc)
    logits = out.logits[:, -1, :]
    binary = torch.stack([logits[:, zero_id], logits[:, one_id]], dim=-1)
    probs = torch.softmax(binary.float(), dim=-1)
    pred = torch.argmax(probs, dim=-1)
    rows = []
    for j, obj in enumerate(batch):
        p0 = float(probs[j,0].detach().cpu()); p1 = float(probs[j,1].detach().cpu()); y = int(pred[j].detach().cpu())
        rows.append({"psg_pred": y, "p0": p0, "p1": p1, "margin_1_minus_0": p1-p0, "raw_generation": str(y), "mode":"logits", "metadata": obj.get("metadata", {})})
    return rows

@torch.inference_mode()
def predict_generate(tok, model, device, batch, max_length, max_new_tokens):
    prompts = [build_prompt(tok, x) for x in batch]
    enc = tok(prompts, return_tensors="pt", padding=True, truncation=True, max_length=max_length)
    enc = {k:v.to(device) for k,v in enc.items()}
    gen = model.generate(**enc, max_new_tokens=max_new_tokens, do_sample=False, temperature=None, top_p=None, pad_token_id=tok.pad_token_id, eos_token_id=tok.eos_token_id)
    input_len = enc["input_ids"].shape[1]
    rows = []
    for j, obj in enumerate(batch):
        text = tok.decode(gen[j, input_len:], skip_special_tokens=True).strip()
        m = re.search(r"[01]", text)
        y = int(m.group(0)) if m else 0
        rows.append({"psg_pred": y, "p0": None, "p1": None, "margin_1_minus_0": None, "raw_generation": text, "mode":"generate", "metadata": obj.get("metadata", {})})
    return rows

def update_stats(stats, rec):
    y = rec["psg_pred"]; meta = rec.get("metadata", {})
    stats["total"] += 1; stats["pred_counts"][str(y)] += 1
    stats["bucket_counts"][str(meta.get("candidate_bucket", "unknown"))] += 1
    stats["minor_counts"][str(bool(meta.get("is_minor", False)))] += 1
    for d in meta.get("triggered_dims", []) or []:
        stats["triggered_dims"][str(d)] += 1

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model_path", required=True)
    ap.add_argument("--adapter_path", default="")
    ap.add_argument("--tokenizer_path", default=None)
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--summary_json", default="")
    ap.add_argument("--mode", choices=["logits", "generate"], default="logits")
    ap.add_argument("--batch_size", type=int, default=2)
    ap.add_argument("--max_length", type=int, default=3072)
    ap.add_argument("--max_new_tokens", type=int, default=2)
    ap.add_argument("--max_samples", type=int, default=-1)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--dtype", choices=["auto", "bf16", "fp16", "fp32"], default="bf16")
    ap.add_argument("--trust_remote_code", action="store_true", default=True)
    ap.add_argument("--flush_every", type=int, default=100)
    args = ap.parse_args()
    tok, model, device, zero_id, one_id = load_model(args)
    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    stats = {"total":0, "pred_counts":Counter(), "bucket_counts":Counter(), "minor_counts":Counter(), "triggered_dims":Counter()}
    t0 = time.time(); done = 0
    with open(args.output, "w", encoding="utf-8") as f:
        for batch in batched(read_jsonl(args.input, args.max_samples), args.batch_size):
            rows = predict_logits(tok, model, device, batch, zero_id, one_id, args.max_length) if args.mode == "logits" else predict_generate(tok, model, device, batch, args.max_length, args.max_new_tokens)
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
                update_stats(stats, r); done += 1
            if done % args.flush_every == 0:
                f.flush(); print(f"[progress] done={done} elapsed={time.time()-t0:.1f}s")
    summary = {"input":args.input, "output":args.output, "total":stats["total"], "pred_counts":dict(stats["pred_counts"]), "bucket_counts":dict(stats["bucket_counts"]), "minor_counts":dict(stats["minor_counts"]), "triggered_dims":dict(stats["triggered_dims"]), "args":vars(args)}
    if args.summary_json:
        os.makedirs(os.path.dirname(args.summary_json) or ".", exist_ok=True)
        with open(args.summary_json, "w", encoding="utf-8") as f: json.dump(summary, f, ensure_ascii=False, indent=2)
        print(f"[write] {args.summary_json}")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
if __name__ == "__main__": main()
